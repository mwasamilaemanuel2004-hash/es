export const generateStrategyVariants = (market: string, regime: string): StrategyCandidate[] => {
    const base = strategyLibrary.map((name, index) => ({
        id: `${market.toLowerCase()}-${index + 1}`,
        name,
        market,
        score: 72 + (index % 8) * 2,
        regime,
        hybrid: index % 3 === 0,
        rationale: [
            'Compatible with target market structure.',
            'Follows validated signal integrity rules.',
            'Passes adaptive regime filters.',
        ],
    }));

    return base.sort((a, b) => b.score - a.score).slice(0, 8);
};

export const createHybridStrategy = (components: StrategyFamily[]) => {
    const unique = [...new Set(components)];

    return {
        name: `Hybrid ${unique[0] ?? 'Strategy'} Engine`,
        components: unique,
        hybrid: unique.length > 1,
        score: 85 + unique.length,
        rationale: 'Hybrid strategy generated by combining compatible components while preserving hard risk checks and validation routes.',
    };
};
